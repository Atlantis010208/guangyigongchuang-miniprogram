function generate() {
  const routes = [...app.pages, ...(app.subpackages || []).flatMap(pkg => pkg.pages.map(page => pkg.root.replace(/\/$/, '') + '/' + page))]
  const titles = {}
  for (const route of routes) {
    const config = JSON.parse(fs.readFileSync(path.join(root, route + '.json'), 'utf8'))
    const title = config.navigationBarTitleText
    titles[route] = title && !title.includes('光乙') ? title : fallback[route]
    if (!titles[route]) throw new Error('Missing navigation title: ' + route)
  }
  return '// Generated by scripts/generate-page-navigation-titles.js; do not edit.\nmodule.exports = ' + JSON.stringify(titles, null, 2) + '\n'
}
if (require.main === module) {
  fs.writeFileSync(path.join(root, 'config/page-navigation-titles.js'), generate())
}
module.exports = generate
