const assert = require('assert')
const { DEFAULT_CONFIG, openidHash, stableBucket, evaluateGate } = require('../cloudfunctions/ui_release_gate/policy')
assert.strictEqual(evaluateGate(DEFAULT_CONFIG, 'user').ownerEnabled, false)
assert.strictEqual(stableBucket('user'), stableBucket('user'))
const hash = openidHash('white-user')
const white = evaluateGate({ enabled:true, uiVersion:'v2', ownerEnabled:true, ownerPercent:0, ownerWhitelistHashes:[hash] }, 'white-user')
assert.strictEqual(white.ownerEnabled, true)
assert.strictEqual(white.designerEnabled, false)
assert.strictEqual(white.ownerWhitelisted, true)
assert.strictEqual(white.designerWhitelisted, false)
const designerWhite = evaluateGate({ enabled:true, uiVersion:'v2', designerEnabled:true, designerPercent:0, designerWhitelistHashes:[hash] }, 'white-user')
assert.strictEqual(designerWhite.ownerEnabled, false)
assert.strictEqual(designerWhite.designerEnabled, true)
const full = evaluateGate({ enabled:true, ownerEnabled:true, designerEnabled:true, ownerPercent:100, designerPercent:100 }, 'any')
assert.strictEqual(full.ownerEnabled, true)
assert.strictEqual(full.designerEnabled, true)
