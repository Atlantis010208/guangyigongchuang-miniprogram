function hasValidCoordinates(lat, lng) {
  return Number.isFinite(lat) && lat >= -90 && lat <= 90 &&
    Number.isFinite(lng) && lng >= -180 && lng <= 180
}

function coordinatesMatchCountry(countryCode, lat, lng) {
  if (!hasValidCoordinates(lat, lng)) return false
  const bounds = COUNTRY_BOUNDS[String(countryCode || '').trim().toUpperCase()]
  if (!bounds) return false
  const longitudeMatches = bounds.minLng <= bounds.maxLng
    ? lng >= bounds.minLng && lng <= bounds.maxLng
    : lng >= bounds.minLng || lng <= bounds.maxLng
  return Boolean(
    lat >= bounds.minLat && lat <= bounds.maxLat &&
    longitudeMatches)
}

